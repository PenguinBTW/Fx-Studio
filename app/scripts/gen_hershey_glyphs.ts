// Generates src/engine/hersheyglyphs.ts from Hershey Sans 1-stroke (public domain-style licence, see the SVG header).
import { readFileSync, writeFileSync } from 'node:fs';
const svg = readFileSync('public/fonts/stroke/HersheySans1.svg', 'utf8');
const dec = (s: string) => s.replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
  .replace(/&apos;/g, "'").replace(/&amp;/g, '&').replace(/&quot;/g, '"').replace(/&lt;/g, '<').replace(/&gt;/g, '>');
const want = new Set<string>();
for (let c = 33; c < 127; c++) want.add(String.fromCharCode(c));
for (const c of '°–—“”') want.add(c);
const lines: string[] = [];
for (const m of svg.matchAll(/<glyph unicode="([^"]*)"[^>]*?(?:horiz-adv-x="([\d.]+)")?[^>]*?\sd="([^"]*)"/g)) {
  const ch = dec(m[1]!);
  if (!want.has(ch)) continue;
  const adv = Number(/horiz-adv-x="([\d.]+)"/.exec(m[0])![1]);
  const strokes: number[][] = [];
  for (const tok of m[3]!.matchAll(/([ML])\s*([-\d.]+)\s+([-\d.]+)/g)) {
    if (tok[1] === 'M') strokes.push([]);
    strokes[strokes.length - 1]!.push(Number(tok[2]), Number(tok[3]));
  }
  lines.push(`  ${JSON.stringify(ch)}: [${adv}, ${JSON.stringify(strokes)}],`);
  want.delete(ch);
}
if (want.size) console.warn('missing', [...want].join(''));
writeFileSync('src/engine/hersheyglyphs.ts',
`// Generated by scripts/gen_hershey_glyphs.ts from Hershey Sans 1-stroke. Units: 1000/em, y up, cap height 662.
// Each glyph: [advance, polylines as flat x,y arrays].
export const HERSHEY_CAP = 662;
export const HERSHEY_GLYPHS: Record<string, [number, number[][]]> = {
${lines.join('\n')}
};
`);
console.log('glyphs', lines.length);
