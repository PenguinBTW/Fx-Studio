cyl('base', 0.45, 0.3, (0, 0, 0.15), DK, bev=0.03)
j1 = empty('j1', (0, 0, 0.3))
t = cyl('turret', 0.32, 0.3, (0, 0, 0.45), YEL, bev=0.03); parent(t, j1)
j2 = empty('j2', (0, 0, 0.65)); parent(j2, j1)
s = cyl('shoulder', 0.2, 0.5, (0, 0, 0.65), CH, rot=(math.pi / 2, 0, 0)); parent(s, j2)
l1 = box('link1', (0.26, 0.3, 1.3), (0, 0, 1.3), YEL, bev=0.05); parent(l1, j2)
