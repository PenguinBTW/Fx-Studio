// Standalone transition blocks: first-class timeline citizens that own the
// seam between two scenes, so scenes stay pure (no transition code inside
// scene modules). A transition receives BOTH scenes' frames plus a driver
// to re-render either scene at any time t (object-level choreography),
// which texture-only crossfades cannot do.
//
// Power rule (same class as the adaptive-sampling ban): transitions may
// only drive STATELESS scenes — evaluating a stateful scene at off-path
// times corrupts its integrated state. The engine throws loudly when a
// transition window opens over a stateful participant.
import type * as THREE from 'three';
import { smoothstep } from './util';
import type { Compositor } from './gl';
import type { Frame, PostOverrides } from './scene';
import type { TimelineEntry } from './engine';

export interface TransitionCtx {
  renderer: THREE.WebGLRenderer;
  comp: Compositor;
  W: number;
  H: number;
}

/** What the engine hands a transition for its window. */
export interface TransitionAPI {
  /** 0..1 progress across the transition window. */
  u: number;
  /** Entry ids on either side of the seam. */
  from: string;
  to: string;
  /**
   * Re-render a participant scene at ANY time into an engine-managed
   * scratch target and return its texture. The frame is built through the
   * same path as normal rendering (same dt semantics, telemetry merge,
   * rec.lastT bookkeeping) — never call scene.render directly.
   */
  sampleScene(id: string, t: number): THREE.Texture;
}

export interface Transition {
  render(
    f: Frame,
    out: THREE.WebGLRenderTarget,
    a: THREE.Texture,
    b: THREE.Texture,
    api: TransitionAPI,
  ): PostOverrides | void;
}

export type TransitionClass = new (ctx: TransitionCtx) => Transition;

/**
 * A transition window on the timeline. `start`/`end` must lie inside BOTH
 * participant entries; `from` must start first. When no entry matches,
 * `id` is generated by the manifest builder.
 */
export interface TransitionEntry {
  id: string;
  from: string;
  to: string;
  start: number;
  end: number;
  load: () => Promise<{ default: TransitionClass }>;
}

/**
 * Overlay-text duck factor from the entry overlap signals (`Frame.tin` /
 * `Frame.tout`). Broadcast convention: outgoing overlays exit fast (gone by
 * 35% through the exit), incoming overlays enter late (silent until 55%
 * through the entrance), so the two are never legible at the same instant
 * and transition seams never show text mush. Returns 1 outside overlaps
 * (tin = 1, tout = 0). Scenes stay pure: the engine (or the DSL wrapper)
 * applies this to overlay text/cards; 3D content is untouched.
 */
export function overlayTextDuck(tin: number, tout: number): number {
  const outK = 1 - smoothstep(0, 0.35, tout);
  const inK = smoothstep(0.55, 1, tin);
  return Math.min(1, Math.max(0, outK * inK));
}

/** 0..1 progress of t across the window (0 outside). */
export function transitionProgress(tr: TransitionEntry, t: number): number {
  if (!(tr.end > tr.start)) return 0;
  return Math.min(1, Math.max(0, (t - tr.start) / (tr.end - tr.start)));
}

/** First (earliest-starting) transition whose window contains t. */
export function resolveTransitionAt(
  transitions: TransitionEntry[],
  t: number,
): TransitionEntry | undefined {
  let best: TransitionEntry | undefined;
  for (const tr of transitions) {
    if (t >= tr.start && t < tr.end && (!best || tr.start < best.start)) best = tr;
  }
  return best;
}

/** Manifest-time geometry checks. Returns human-readable errors (empty = valid). */
export function validateTransition(
  tr: { id: string; from: string; to: string; start: number; end: number },
  entries: TimelineEntry[],
): string[] {
  const errors: string[] = [];
  const byId = new Map(entries.map((e) => [e.id, e]));
  const a = byId.get(tr.from);
  const b = byId.get(tr.to);
  if (!a) errors.push(`transition '${tr.id}': unknown from-entry '${tr.from}'`);
  if (!b) errors.push(`transition '${tr.id}': unknown to-entry '${tr.to}'`);
  if (tr.from === tr.to) errors.push(`transition '${tr.id}': from and to are both '${tr.from}'`);
  if (!(tr.end > tr.start)) errors.push(`transition '${tr.id}': empty window [${tr.start}, ${tr.end}]`);
  if (a && (tr.start < a.start || tr.end > a.end)) {
    errors.push(`transition '${tr.id}': window [${tr.start}, ${tr.end}] outside '${a.id}' [${a.start}, ${a.end}]`);
  }
  if (b && (tr.start < b.start || tr.end > b.end)) {
    errors.push(`transition '${tr.id}': window [${tr.start}, ${tr.end}] outside '${b.id}' [${b.start}, ${b.end}]`);
  }
  if (a && b && a.start > b.start) {
    errors.push(`transition '${tr.id}': from-entry '${a.id}' must start before to-entry '${b.id}'`);
  }
  return errors;
}
